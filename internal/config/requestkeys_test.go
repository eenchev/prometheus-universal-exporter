// updateRequestKeys has TestTheRequestKeyCatalogueIsCurrent write the
// catalogue rather than compare it, as make schemas runs it.
var updateRequestKeys = flag.Bool("update-request-keys", false, "write internal/fetch/requestkeys_catalogue.go from this build, which must have every request type")

// catalogueFile is the catalogue, from this package's directory.
const catalogueFile = "../fetch/requestkeys_catalogue.go"

// The catalogue of the request types' own keys
// (internal/fetch/requestkeys_catalogue.go) is what the built types' structs
// and key rules give: each built type's keys, with the Go types of their
// fields and their schemas, are in it as they are made now, and a build
// with every request type makes the whole file. Regenerate it with make
// schemas.
func TestTheRequestKeyCatalogueIsCurrent(t *testing.T) {
	if *updateRequestKeys {
		generated, err := requestKeyCatalogueSource()
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(catalogueFile, generated, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	built := map[string]bool{}
	for _, rt := range fetch.OwnKeyTypes() {
		built[rt.Name] = true
	}
	var catalogued []fetch.RequestKeyEntry
	for _, entry := range fetch.RequestKeyCatalogue() {
		if built[entry.Type] {
			catalogued = append(catalogued, entry)
		}
	}
	made := builtRequestKeyEntries()
	// The schema of request.driver names the drivers the build carries,
	// and the catalogue is made from a build with the default ones: in a
	// build with opt-in drivers, the schemas are not compared.
	if fetch.RequestTypes[fetch.RequestTypeSQL] != nil && !slices.Equal(fetch.BuiltSQLDrivers(), []string{fetch.SQLDriverMySQL, fetch.SQLDriverPostgres, fetch.SQLDriverSQLServer}) {
		for _, entries := range [][]fetch.RequestKeyEntry{made, catalogued} {
			for i := range entries {
				entries[i].Schema = ""
			}
		}
	}
	if !slices.Equal(made, catalogued) {
		t.Fatal("internal/fetch/requestkeys_catalogue.go is out of date for the request types of this build; regenerate it with: make schemas")
	}
	if len(fetch.UnbuiltRequestTypes()) > 0 {
		return
	}
	generated, err := requestKeyCatalogueSource()
	if err != nil {
		t.Fatal(err)
	}
	committed, err := os.ReadFile(catalogueFile)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(committed, generated) {
		t.Fatal("internal/fetch/requestkeys_catalogue.go is out of date; regenerate it with: make schemas")
	}
}

// requestKeyCatalogueSource is the catalogue of the own keys of every
// request type of the tree (fetch.RequestKeyCatalogue), as the Go source of
// internal/fetch/requestkeys_catalogue.go: each key of each built type's own
// with the Go type of its field and its schema. make schemas writes it from
// a build with every request type, which it must be made from: it fails in
// any other.
func requestKeyCatalogueSource() ([]byte, error) {
	if unbuilt := fetch.UnbuiltRequestTypes(); len(unbuilt) > 0 {
		return nil, fmt.Errorf("the catalogue of request keys is made from a build with every request type; this one leaves out %s", strings.Join(unbuilt, ", "))
	}
	var b strings.Builder
	b.WriteString(`// Code generated by make schemas (TestTheRequestKeyCatalogueIsCurrent in internal/config, with -update-request-keys) from a build with every request type; DO NOT EDIT.

package fetch

// requestKeysCatalogue is the own keys of every request type of the source
// tree, each with the Go type of the field it is read into and its schema,
// as a build with every request type has them (requestkeys.go).
var requestKeysCatalogue = []RequestKeyEntry{
`)
	for _, entry := range builtRequestKeyEntries() {
		fmt.Fprintf(&b, "\t{Type: %q, Key: %q, GoType: %q, Shape: %s, Schema: %s},\n", entry.Type, entry.Key, entry.GoType, quoted(entry.Shape), quoted(entry.Schema))
	}
	b.WriteString("}\n")
	return format.Source([]byte(b.String()))
}

// builtRequestKeyEntries are the catalogue's entries of the built types,
// in the catalogue's order.
func builtRequestKeyEntries() []fetch.RequestKeyEntry {
	const path = "collectors[].request"
	entries := []fetch.RequestKeyEntry{}
	for _, rt := range fetch.OwnKeyTypes() {
		schemas := ownKeySchemas(rt, path, configSchemaRules())
		own := reflect.TypeOf(rt.Config)
		for _, key := range rt.OwnKeys() {
			field, _ := ownField(own, key)
			schema, err := json.Marshal(schemas[key])
			if err != nil {
				panic(err)
			}
			shape, err := fetch.GoTypeShape(field.Type)
			if err != nil {
				panic(err)
			}
			entries = append(entries, fetch.RequestKeyEntry{Type: rt.Name, Key: key, GoType: field.Type.String(), Shape: shape, Schema: string(schema)})
		}
	}
	return entries
}

// ownField is the field of the struct own whose yaml key is key.
func ownField(own reflect.Type, key string) (reflect.StructField, bool) {
	for i := 0; i < own.NumField(); i++ {
		if name, _, _ := strings.Cut(own.Field(i).Tag.Get("yaml"), ","); name == key {
			return own.Field(i), true
		}
	}
	return reflect.StructField{}, false
}

// quoted is text as a Go literal: in backquotes, unless it holds one.
func quoted(text string) string {
	if strconv.CanBackquote(text) {
		return "`" + text + "`"
	}
	return strconv.Quote(text)
}
